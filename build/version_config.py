def generate_launcher_version_header() -> str:
    """Generate version header for desktop_launcher.py."""
    return f'__version__ = "{get_version_string()}"'


# =============================================================================
# CLI - Generate all version files
# =============================================================================

if __name__ == "__main__":
    from pathlib import Path
    
    build_dir = Path(__file__).parent
    
    print(f"NormCode Canvas Version: {VERSION}")
    print(f"Version Tuple: {VERSION_TUPLE}")
    print()
    
    # Generate version_info.txt
    version_info_path = build_dir / "version_info.txt"
    version_info_path.write_text(generate_version_info_txt(), encoding="utf-8")
    print(f"[OK] Generated: {version_info_path}")
    
    # Generate installer.iss
    installer_path = build_dir / "installer.iss"
    installer_path.write_text(generate_installer_iss(), encoding="utf-8")
    print(f"[OK] Generated: {installer_path}")
    
    # Update desktop_launcher.py version
    launcher_path = build_dir / "launcher" / "desktop_launcher.py"
    if launcher_path.exists():
        content = launcher_path.read_text(encoding="utf-8")
        import re
        new_content = re.sub(
            r'^__version__\s*=\s*["\'].*["\']',
            generate_launcher_version_header(),
            content,
            flags=re.MULTILINE
        )
        if new_content != content:
            launcher_path.write_text(new_content, encoding="utf-8")
            print(f"[OK] Updated: {launcher_path}")
        else:
            print(f"[--] No change: {launcher_path}")
    
    print()
    print("Done! Version files are now synchronized.")

