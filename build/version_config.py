"""
NormCode Canvas - Centralized Version Configuration
====================================================

This is the SINGLE SOURCE OF TRUTH for all version information.
All build scripts and generated files pull from these constants.

To update the version:
1. Edit the values in this file
2. Run: python generate_version_files.py
   (This regenerates version_info.txt and installer.iss)

Or simply run the build script which auto-generates these files.
"""

# =============================================================================
# VERSION CONFIGURATION - Edit these values to update the version
# =============================================================================

VERSION_MAJOR = 1
VERSION_MINOR = 0
VERSION_PATCH = 5
VERSION_BUILD = 0  # For Windows file versioning (usually 0)

# Pre-release tag: "alpha", "beta", "rc1", "" (empty for release)
VERSION_PRERELEASE = "alpha"

# =============================================================================
# APPLICATION METADATA
# =============================================================================

APP_NAME = "NormCode Canvas"
APP_INTERNAL_NAME = "NormCodeCanvas"
APP_DESCRIPTION = "NormCode Canvas - Visual Agent Builder"
APP_PUBLISHER = "NormCode"
APP_COPYRIGHT = "Copyright (c) 2024-2026 Psylens.AI"
APP_URL = "https://github.com/normcode"

# Windows-specific
APP_BUNDLE_GUID = "{B8F3D2A1-5C4E-4F2B-9A1D-3E2C1F0A9B8D}"

# macOS-specific
APP_BUNDLE_ID = "com.normcode.canvas"

# =============================================================================
# COMPUTED VERSION STRINGS (Do not edit below)
# =============================================================================

def get_version_string() -> str:
    """Get the full version string (e.g., '1.0.5-alpha' or '1.0.0')."""
    base = f"{VERSION_MAJOR}.{VERSION_MINOR}.{VERSION_PATCH}"
    if VERSION_PRERELEASE:
        return f"{base}-{VERSION_PRERELEASE}"
    return base


def get_version_tuple() -> tuple:
    """Get version as tuple for Windows versioning (major, minor, patch, build)."""
    return (VERSION_MAJOR, VERSION_MINOR, VERSION_PATCH, VERSION_BUILD)


def get_windows_flags() -> int:
    """Get Windows version flags (VS_FF_PRERELEASE for alpha/beta)."""
    if VERSION_PRERELEASE:
        return 0x2  # VS_FF_PRERELEASE
    return 0x0


# Convenient exports
VERSION = get_version_string()
VERSION_TUPLE = get_version_tuple()


# =============================================================================
# VERSION FILE GENERATORS
# =============================================================================

def generate_version_info_txt() -> str:
    """Generate content for Windows version_info.txt (PyInstaller format)."""
    ver = get_version_tuple()
    flags = get_windows_flags()
    version_str = get_version_string()
    
    return f'''# UTF-8
#
# Windows Version Information for {APP_NAME}
# This file is auto-generated by version_config.py - DO NOT EDIT DIRECTLY
#

VSVersionInfo(
  ffi=FixedFileInfo(
    # filevers and prodvers should be always a tuple with four items: (1, 2, 3, 4)
    filevers={ver},
    prodvers={ver},
    # Contains a bitmask that specifies the valid bits 'flags'
    mask=0x3f,
    # Contains a bitmask that specifies the Boolean attributes of the file
    # VS_FF_PRERELEASE (0x2) for alpha/beta versions
    flags={hex(flags)},
    # The operating system for which this file was designed
    # 0x40004 - NT and target is Windows NT
    OS=0x40004,
    # The general type of file
    # 0x1 - the file is an application
    fileType=0x1,
    # The function of the file
    subtype=0x0,
    # Creation date and time stamp
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          u'040904B0',
          [
            StringStruct(u'CompanyName', u'{APP_PUBLISHER}'),
            StringStruct(u'FileDescription', u'{APP_DESCRIPTION}'),
            StringStruct(u'FileVersion', u'{version_str}'),
            StringStruct(u'InternalName', u'{APP_INTERNAL_NAME}'),
            StringStruct(u'LegalCopyright', u'{APP_COPYRIGHT}'),
            StringStruct(u'OriginalFilename', u'{APP_INTERNAL_NAME}.exe'),
            StringStruct(u'ProductName', u'{APP_NAME}'),
            StringStruct(u'ProductVersion', u'{version_str}'),
          ]
        )
      ]
    ),
    VarFileInfo([VarStruct(u'Translation', [1033, 1200])])
  ]
)
'''


